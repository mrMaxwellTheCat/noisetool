def generate_grey_noise(
    n_samples: int,
    n_channels: int = 2,
    *,
    rng: np.random.Generator | None = None,
) -> np.ndarray:
    """Grey noise: psychoacoustic equal-loudness noise.

    Generated via frequency-domain filtering: FFT of white noise
    multiplied by a 1/(1+(f/2000)^2) filter, then inverse FFT.

    Args:
        n_samples: Number of audio samples to generate.
        n_channels: Number of channels (1=mono, 2=stereo).
        rng: Optional numpy random generator for reproducibility.

    Returns:
        Float32 array of shape (n_samples, n_channels) normalized to [-1, 1].
    """
    if rng is None:
        rng = np.random.default_rng()
    if n_samples <= 0:
        raise ValueError(f"n_samples must be > 0, got {n_samples}")
    if n_channels not in (1, 2):
        raise ValueError(f"n_channels must be 1 or 2, got {n_channels}")

    white = rng.uniform(-1.0, 1.0, (n_samples, n_channels)).astype(np.float64)

    freq = np.fft.rfftfreq(n_samples, d=1.0 / SAMPLE_RATE)
    freq[0] = freq[1]
    grey_filter = 1.0 / (1.0 + (freq / 2000.0) ** 2)

    grey = np.empty_like(white)
    for ch in range(n_channels):
        fft = np.fft.rfft(white[:, ch])
        fft *= grey_filter
        grey[:, ch] = np.fft.irfft(fft, n=n_samples)

    max_val = np.max(np.abs(grey))
    if max_val > 0:
        grey /= max_val
    return grey.astype(np.float32)
